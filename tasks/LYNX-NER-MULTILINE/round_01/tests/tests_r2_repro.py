"""F1: valid detector boundary -> real pipeline/Guard; synthetic data only.

Controlled NERResult isolates the changed owner's behavior; this is not evidence
that this exact boundary was generated by real SpaCy in a document.
Run from repository root with the installed backend Python environment.
"""
import contextlib
import io
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import types
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[4]
BASE = "c62f819"
HEAD = "6cf403eab798d5391c5dc76cd01188cde1066a29"
sys.path[:0] = [str(ROOT / "backend"), str(ROOT / "audyt")]


def main():
    with contextlib.redirect_stdout(io.StringIO()), contextlib.redirect_stderr(io.StringIO()):
        import engine_quality
        import ner_layer
        import pipeline
        import spacy_ner
    baseline = types.ModuleType("retained_multiline_baseline")
    baseline.__file__ = str(ROOT / "backend/ner_layer.py")
    sys.modules[baseline.__name__] = baseline
    source = subprocess.check_output(
        ["git", "show", f"{BASE}:backend/ner_layer.py"], cwd=ROOT
    ).decode("utf-8")
    pinned = subprocess.check_output(
        ["git", "show", f"{HEAD}:backend/ner_layer.py"], cwd=ROOT
    ).decode("utf-8")
    assert (ROOT / "backend/ner_layer.py").read_text(encoding="utf-8") == pinned
    exec(compile(source, baseline.__file__, "exec"), baseline.__dict__)
    variants = [
        ("single-line-control", "Testopolia Systemy", False),
        ("trailing-LF", "Testopolia Systemy\n", True),
        ("trailing-CRLF", "Testopolia Systemy\r\n", True),
        ("leading-LF", "\nTestopolia Systemy", True),
        ("one-word-trailing-LF", "Testopolia\n", True),
        ("legal-form-control", "Testopolia Systemy Sp. z o.o.\n", False),
    ]
    rows = []
    with tempfile.TemporaryDirectory(prefix="lynx_multiline_f1_") as folder:
        with contextlib.redirect_stdout(io.StringIO()), contextlib.redirect_stderr(io.StringIO()):
            state = engine_quality.build_state(folder)
        for label, span, regression in variants:
            text = "Wykonawca: " + span + "; koniec."
            start = text.index(span)
            entity = spacy_ner.NERResult(
                text=span, label="FIRMA", confidence=.9,
                start=start, end=start + len(span),
            )
            row = {"case": label}
            for name, owner in (("base", baseline._process_ner), ("head", ner_layer._process_ner)):
                with patch.object(spacy_ner, "detect_entities", return_value=[entity]), \
                        patch.object(ner_layer, "_process_ner", owner), \
                        contextlib.redirect_stdout(io.StringIO()), contextlib.redirect_stderr(io.StringIO()):
                    result = pipeline.pseudonymize_document(text, state)
                row[name] = dict(raw_company="Testopolia" in result.text,
                                 guard_blocked=result.guard_blocked,
                                 error=bool(result.error), map_entries=len(result.reverse_map))
            assert not row["base"]["raw_company"]
            assert row["head"]["raw_company"] == regression
            assert not any(row[r]["guard_blocked"] or row[r]["error"] for r in ("base", "head"))
            assert row["head"]["map_entries"] == (0 if regression else 1)
            rows.append(row)
    print(json.dumps({"sha": HEAD, "controlled_detector": True, "cases": rows}))


if __name__ == "__main__":
    main()
